//for loops

for (let i = 0; i < 5; i++) {
    console.log(i);
}
console.log('Loop is done!');
console.log('--------------------');
console.log('Loop is Finished!');

const names = ['shaun', 'mario', 'luigi'];
for (let i = 0; i < names.length; i++) {
    console.log(i);
    console.log(names[i]);
} 

//while loops

let j = 0;

while (j < 5) {
    console.log(j);
    j++;
}
console.log('While loop is done!');
console.log('--------------------');
console.log('While loop is Finished!');

const names2 = ['shaun', 'mario', 'luigi'];
let k = 0;

while (k < names2.length) {
    console.log(k);
    console.log(names2[k]);
    k++;
}

